// Embed every theme's sample.json for the demo Worker (demo/samples.gen.ts),
// and each look's credit from themes/credits.json (an X handle, checked).
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseCredits } from "./catalog.mjs";

const root = new URL("../../themes/", import.meta.url).pathname;
const out = {};
const names = readdirSync(root).filter((name) => statSync(join(root, name)).isDirectory());
for (const name of names) {
  const f = join(root, name, "sample.json");
  if (existsSync(f)) out[name] = JSON.parse(readFileSync(f, "utf8"));
}
// Sample photos (themes/<look>/sample-media), base64, for looks whose sample.json uses /media/ paths.
const media = {};
for (const name of names) {
  const d = join(root, name, "sample-media");
  if (!existsSync(d)) continue;
  for (const f of readdirSync(d)) {
    if (!/^[0-9a-f]{32}\.(jpg|png|webp)$/.test(f)) continue;
    (media[name] ??= {})[f] = readFileSync(join(d, f)).toString("base64");
  }
}
writeFileSync(
  new URL("../demo/media.gen.ts", import.meta.url),
  `// Generated by scripts/demo-gen.mjs. Don't edit by hand.\nexport const MEDIA: Record<string, Record<string, string>> = ${JSON.stringify(media)};\n`,
);
const creditsFile = join(root, "credits.json");
const credits = parseCredits(existsSync(creditsFile) ? readFileSync(creditsFile, "utf8") : "{}", names);
writeFileSync(
  new URL("../demo/samples.gen.ts", import.meta.url),
  `// Generated by scripts/demo-gen.mjs. Don't edit by hand.\nexport const SAMPLES: Record<string, any> = ${JSON.stringify(out)};\nexport const CREDITS: Record<string, string> = ${JSON.stringify(credits)};\n`,
);
console.log(`demo samples: ${Object.keys(out).join(", ")}; credited: ${Object.keys(credits).length}`);
