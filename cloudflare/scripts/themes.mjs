// Embed every theme under themes/ into src/themes.gen.ts, so the Worker is
// one file with no build-time asset handling. Run after changing a theme.
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join } from "node:path";

const root = new URL("../../themes/", import.meta.url).pathname;
const out = {};
for (const name of readdirSync(root)) {
  const dir = join(root, name);
  if (!statSync(dir).isDirectory()) continue;
  const read = (sub, ext) => {
    const d = join(dir, sub);
    let files = [];
    try { files = readdirSync(d); } catch { return {}; }
    return Object.fromEntries(files.filter((f) => !ext || f.endsWith(ext)).map((f) => [ext ? f.slice(0, -ext.length) : f, readFileSync(join(d, f), "utf8")]));
  };
  out[name] = {
    manifest: JSON.parse(readFileSync(join(dir, "template.json"), "utf8")),
    pages: read("", ".mustache"),
    partials: read("partials", ".mustache"),
    static: read("static", ""),
  };
}
writeFileSync(
  new URL("../src/themes.gen.ts", import.meta.url),
  `// Generated by scripts/themes.mjs from themes/. Don't edit by hand.\nexport const THEMES: Record<string, { manifest: Record<string, unknown>; pages: Record<string, string>; partials: Record<string, string>; static: Record<string, string> }> = ${JSON.stringify(out, null, 1)};\n`,
);
console.log(`themes: ${Object.keys(out).join(", ")}`);
